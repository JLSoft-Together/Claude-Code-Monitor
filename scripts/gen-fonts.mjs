// Writes apps/web/src/fonts.css (bundled faces, latin + latin-ext + vietnamese only, upright only) and
// apps/web/public/fonts-LICENSES.txt from the @fontsource packages of apps/web. Run after changing the list:
//   node scripts/gen-fonts.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const web = path.join(root, 'apps/web')
const require = createRequire(path.join(web, 'package.json'))

/** pkg, css files to read, family as used in lib/fonts.ts. Mirrors the `bundled` entries of lib/fonts.ts (checked by fonts.test.ts). */
export const FONTS = [
  ['@fontsource-variable/jetbrains-mono', ['wght.css'], 'JetBrains Mono Variable'],
  ['@fontsource-variable/google-sans-code', ['wght.css'], 'Google Sans Code Variable'],
  ['@fontsource-variable/cascadia-code', ['wght.css'], 'Cascadia Code Variable'],
  ['@fontsource-variable/fira-code', ['wght.css'], 'Fira Code Variable'],
  ['@fontsource-variable/source-code-pro', ['wght.css'], 'Source Code Pro Variable'],
  ['@fontsource/ibm-plex-mono', ['400.css', '500.css', '600.css'], 'IBM Plex Mono'],
  ['@fontsource-variable/roboto-mono', ['wght.css'], 'Roboto Mono Variable'],
  ['@fontsource-variable/geist-mono', ['wght.css'], 'Geist Mono Variable'],
  ['@fontsource/ubuntu-mono', ['400.css', '700.css'], 'Ubuntu Mono'],
  ['@fontsource-variable/inconsolata', ['wght.css'], 'Inconsolata Variable'],
  ['@fontsource-variable/google-sans-flex', ['wght.css'], 'Google Sans Flex Variable'],
  ['@fontsource-variable/inter', ['wght.css'], 'Inter Variable'],
  ['@fontsource-variable/roboto', ['wght.css'], 'Roboto Variable'],
  ['@fontsource-variable/ibm-plex-sans', ['wght.css'], 'IBM Plex Sans Variable'],
  ['@fontsource-variable/source-sans-3', ['wght.css'], 'Source Sans 3 Variable'],
  ['@fontsource-variable/noto-sans', ['wght.css'], 'Noto Sans Variable'],
  ['@fontsource-variable/open-sans', ['wght.css'], 'Open Sans Variable'],
  ['@fontsource/be-vietnam-pro', ['400.css', '500.css', '600.css', '700.css'], 'Be Vietnam Pro'],
]
const SUBSETS = ['latin', 'latin-ext', 'vietnamese']
// Packages whose LICENSE has no copyright line of its own (holders from the upstream font repositories).
const HOLDERS = {
  '@fontsource-variable/cascadia-code': 'Copyright (c) 2019 - Present, Microsoft Corporation, with Reserved Font Name Cascadia Code.',
  '@fontsource-variable/source-code-pro': "Copyright 2010-2020 Adobe (http://www.adobe.com/), with Reserved Font Name 'Source'.",
  '@fontsource-variable/source-sans-3': "Copyright 2010-2020 Adobe (http://www.adobe.com/), with Reserved Font Name 'Source'.",
  '@fontsource/ubuntu-mono': 'Copyright 2010-2011 Canonical Ltd.',
}
const posix = (p) => p.split(path.sep).join('/')

let css = '/* Generated by scripts/gen-fonts.mjs — do not edit. Bundled code / UI fonts (Settings → Appearance). */\n'
let licenses = 'Fonts bundled with Agent Monitor\n================================\n\n'
const texts = new Map()
for (const [pkg, files, family] of FONTS) {
  const dir = path.dirname(require.resolve(`${pkg}/package.json`))
  const rel = posix(path.relative(path.join(web, 'src'), dir))
  let kept = 0
  for (const file of files) {
    const src = readFileSync(path.join(dir, file), 'utf8')
    for (const m of src.matchAll(/\/\* ([a-z0-9-]+) \*\/\s*(@font-face \{[^}]*\})/g)) {
      const [, name, block] = m
      if (!name.endsWith('-normal')) continue
      const subset = SUBSETS.find((s) => new RegExp(`-${s}-(wght|\\d{3})-normal$`).test(name))
      if (!subset) continue
      if (!block.includes(`font-family: '${family}'`)) throw new Error(`${pkg}: family is not ${family}`)
      css += `/* ${name} */\n${block.replace(/url\(\.\/files\//g, `url(${rel}/files/`)}\n`
      kept++
    }
  }
  if (!kept) throw new Error(`${pkg}: no faces kept`)
  const license = readFileSync(path.join(dir, 'LICENSE'), 'utf8').replace(/\r\n/g, '\n')
  const kind = /UBUNTU FONT LICENCE/.test(license) ? 'Ubuntu Font Licence 1.0' : 'SIL Open Font License 1.1'
  // The first line repeats the notice once per .ttf file; the first notice is enough.
  const first = license.split('\n').find((l) => /^Copyright (\d|\(c\))/.test(l))
  const copyright = HOLDERS[pkg] ?? first?.split(/ [\w-]+(?:\[[^\]]*\])?\.ttf:/)[0].trim()
  if (!copyright) throw new Error(`${pkg}: no copyright line`)
  licenses += `${family.replace(/ Variable$/, '')} (${pkg}): ${kind}\n  ${copyright}\n\n`
  if (!texts.has(kind)) texts.set(kind, license.slice(license.search(/(SIL OPEN FONT LICENSE|-+\nUBUNTU FONT LICENCE)/)))
}
for (const [kind, text] of texts) licenses += `\n${kind}\n${'-'.repeat(kind.length)}\n\n${text.trim()}\n`

writeFileSync(path.join(web, 'src/fonts.css'), css)
writeFileSync(path.join(web, 'public/fonts-LICENSES.txt'), licenses)
console.log(`fonts.css: ${FONTS.length} families`)
