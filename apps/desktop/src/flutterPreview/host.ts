import { promises as fs } from 'node:fs'
import path from 'node:path'
import type { FwpEntry } from '@ccm/shared'
import { parsePubspec } from '../run/flutter/detect'

export const HOST_DIR = path.join('.dart_tool', 'ccm_preview')
export const HOST_FILE = 'main.dart'
export const SHOW_EXTENSION = 'ext.ccm.show'
const PACKAGE = /^[a-z_][a-z0-9_]*$/

export interface PubspecPackage {
  name: string
  flutter: boolean
}

export function readPackage(pubspec: string): PubspecPackage | null {
  const info = parsePubspec(pubspec)
  return PACKAGE.test(info.name) ? { name: info.name, flutter: info.flutter } : null
}

const dartString = (s: string): string => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'`

/** Registry is a getter so a hot reload picks up entries added since the last build. */
export function hostSource(pkg: string, entries: readonly FwpEntry[]): string {
  const usable = entries.filter((e) => !e.skipped && e.call)
  const files = [...new Set(usable.map((e) => e.file))]
  const alias = new Map(files.map((f, i) => [f, `p${i}`]))
  const imports = files.map((f) => `import ${dartString(`package:${pkg}/${f.slice('lib/'.length)}`)} as ${alias.get(f)};`)
  const rows = usable.map((e) => `      ${dartString(e.id)}: () => ${alias.get(e.file)}.${e.call},`)
  return `// Generated by Agent Monitor for Flutter widget preview. Changes are overwritten.
// ignore_for_file: type=lint
import 'dart:convert';
import 'dart:developer' as developer;

import 'package:flutter/material.dart';
${imports.join('\n')}${imports.length ? '\n' : ''}
Map<String, Widget Function()> get _previews => <String, Widget Function()>{
${rows.join('\n')}${rows.length ? '\n' : ''}    };

final ValueNotifier<String?> _current = ValueNotifier<String?>(null);

void main() {
  developer.registerExtension('${SHOW_EXTENSION}', (method, params) async {
    final id = params['id'];
    final ok = id != null && _previews.containsKey(id);
    if (ok) _current.value = id;
    return developer.ServiceExtensionResponse.result(jsonEncode(<String, Object>{'ok': ok}));
  });
  runApp(const _PreviewHost());
}

class _PreviewHost extends StatelessWidget {
  const _PreviewHost();

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      debugShowCheckedModeBanner: false,
      home: Scaffold(
        body: SafeArea(
          child: Center(
            child: ValueListenableBuilder<String?>(
              valueListenable: _current,
              builder: (context, id, _) {
                final build = id == null ? null : _previews[id];
                if (build == null) return const Text('Select a widget in Agent Monitor');
                return build();
              },
            ),
          ),
        ),
      ),
    );
  }
}
`
}

/** Writes `<root>/.dart_tool/ccm_preview/main.dart` only when the content changed. */
export async function writeHost(root: string, source: string): Promise<{ file: string; changed: boolean }> {
  const dir = path.join(root, HOST_DIR)
  const file = path.join(dir, HOST_FILE)
  const old = await fs.readFile(file, 'utf8').catch(() => null)
  if (old === source) return { file, changed: false }
  await fs.mkdir(dir, { recursive: true })
  await fs.writeFile(file, source)
  return { file, changed: true }
}
