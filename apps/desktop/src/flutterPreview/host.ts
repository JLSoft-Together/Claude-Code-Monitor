import { promises as fs } from 'node:fs'
import path from 'node:path'
import type { FwpEntry } from '@ccm/shared'
import { parsePubspec, yamlKeys } from '../run/flutter/detect'

export const HOST_DIR = path.join('.dart_tool', 'ccm_preview')
export const HOST_FILE = 'main.dart'
export const SHOW_EXTENSION = 'ext.ccm.show'
/** Line prefix the host prints (JSON follows) when the shown widget throws; arrives as `app.log`. */
export const ERROR_MARKER = 'ccm.error '
const ERROR_CAP = 400
const PACKAGE = /^[a-z_][a-z0-9_]*$/

export interface PubspecPackage {
  name: string
  flutter: boolean
}

export function readPackage(pubspec: string): PubspecPackage | null {
  const info = parsePubspec(pubspec)
  return PACKAGE.test(info.name) ? { name: info.name, flutter: info.flutter } : null
}

const dartString = (s: string): string => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'`

/** What the project's own app would put above a widget (v57). */
export interface HostContext {
  /** `package:…` library exporting `ProviderScope`; each preview gets its own scope. */
  riverpod?: string
  /** gen-l10n output: its `localizationsDelegates` / `supportedLocales` go on the host `MaterialApp`. */
  l10n?: { uri: string; className: string }
}

const RIVERPOD = [
  ['hooks_riverpod', 'package:hooks_riverpod/hooks_riverpod.dart'],
  ['flutter_riverpod', 'package:flutter_riverpod/flutter_riverpod.dart'],
] as const
const DART_IDENT = /^[A-Za-z_$][\w$]*$/
const L10N_FILE = /^[\w-]+\.dart$/
const L10N_DIR = /^lib(?:\/[\w-]+)*$/

const isFile = async (file: string): Promise<boolean> => !!(await fs.stat(file).catch(() => null))?.isFile()

/**
 * Riverpod from the declared dependencies; gen-l10n from `l10n.yaml` (defaults of `flutter gen-l10n`),
 * used when its output exists or `flutter: generate: true` lets `flutter run` write it before the build.
 */
export async function hostContext(root: string, pubspec: string, exists: (file: string) => Promise<boolean> = isFile, readText: (file: string) => Promise<string | null> = (f) => fs.readFile(f, 'utf8').catch(() => null)): Promise<HostContext> {
  const keys = yamlKeys(pubspec)
  const ctx: HostContext = {}
  const riverpod = RIVERPOD.find(([dep]) => keys.has(`dependencies.${dep}`))
  if (riverpod) ctx.riverpod = riverpod[1]
  const yaml = await readText(path.join(root, 'l10n.yaml'))
  if (yaml === null) return ctx
  const l10n = yamlKeys(yaml)
  const file = l10n.get('output-localization-file') || 'app_localizations.dart'
  const className = l10n.get('output-class') || 'AppLocalizations'
  if (!L10N_FILE.test(file) || !DART_IDENT.test(className)) return ctx
  const generate = keys.get('flutter.generate') === 'true'
  if (l10n.get('synthetic-package') === 'true') {
    // Flutter before 3.32: generated into the `flutter_gen` synthetic package.
    if (generate || (await exists(path.join(root, '.dart_tool', 'flutter_gen', 'gen_l10n', file)))) ctx.l10n = { uri: `package:flutter_gen/gen_l10n/${file}`, className }
    return ctx
  }
  // Outside lib/ it has no `package:` URI the host could import.
  const dir = (l10n.get('output-dir') || l10n.get('arb-dir') || 'lib/l10n').replace(/\\/g, '/').replace(/^\.\//, '').replace(/\/+$/, '')
  const pkg = readPackage(pubspec)?.name
  if (!pkg || !L10N_DIR.test(dir)) return ctx
  const sub = dir === 'lib' ? '' : `${dir.slice('lib/'.length)}/`
  if (generate || (await exists(path.join(root, dir, file)))) ctx.l10n = { uri: `package:${pkg}/${sub}${file}`, className }
  return ctx
}

/** Registry is a getter so a hot reload picks up entries added since the last build. */
export function hostSource(pkg: string, entries: readonly FwpEntry[], ctx: HostContext = {}): string {
  const usable = entries.filter((e) => !e.skipped && e.call)
  const files = [...new Set(usable.map((e) => e.file))]
  const alias = new Map(files.map((f, i) => [f, `p${i}`]))
  const imports = files.map((f) => `import ${dartString(`package:${pkg}/${f.slice('lib/'.length)}`)} as ${alias.get(f)};`)
  const rows = usable.map((e) => `      ${dartString(e.id)}: () => ${alias.get(e.file)}.${e.call},`)
  // Prefixed: neither may clash with material.dart or a project library.
  const extra = [...(ctx.riverpod ? [`import ${dartString(ctx.riverpod)} as ccm_riverpod;`] : []), ...(ctx.l10n ? [`import ${dartString(ctx.l10n.uri)} as ccm_l10n;`] : [])]
  const shown = ctx.riverpod ? 'ccm_riverpod.ProviderScope(key: ValueKey<String?>(id), child: build())' : 'build()'
  const l10n = ctx.l10n
    ? `
      localizationsDelegates: ccm_l10n.${ctx.l10n.className}.localizationsDelegates,
      supportedLocales: ccm_l10n.${ctx.l10n.className}.supportedLocales,`
    : ''
  return `// Generated by Orrery for Flutter widget preview. Changes are overwritten.
// ignore_for_file: type=lint
import 'dart:convert';
import 'dart:developer' as developer;

import 'package:flutter/material.dart';
${[...extra, ...imports].join('\n')}${extra.length + imports.length ? '\n' : ''}
Map<String, Widget Function()> get _previews => <String, Widget Function()>{
${rows.join('\n')}${rows.length ? '\n' : ''}    };

final ValueNotifier<String?> _current = ValueNotifier<String?>(null);
String? _reportedFor;

void _report(Object error) {
  final id = _current.value;
  if (id == null || _reportedFor == id) return;
  _reportedFor = id;
  var message = error.toString();
  if (message.length > ${ERROR_CAP}) message = message.substring(0, ${ERROR_CAP});
  print(${dartString(ERROR_MARKER)} + jsonEncode(<String, String>{'id': id, 'message': message}));
}

void main() {
  WidgetsFlutterBinding.ensureInitialized();
  FlutterError.onError = (details) {
    FlutterError.presentError(details);
    _report(details.exceptionAsString());
  };
  WidgetsBinding.instance.platformDispatcher.onError = (error, stack) {
    _report(error);
    return false;
  };
  ErrorWidget.builder = (details) => _ErrorCard(details.exceptionAsString());
  developer.registerExtension('${SHOW_EXTENSION}', (method, params) async {
    final id = params['id'];
    final ok = id != null && _previews.containsKey(id);
    if (ok) {
      _reportedFor = null;
      _current.value = id;
    }
    return developer.ServiceExtensionResponse.result(jsonEncode(<String, Object>{'ok': ok}));
  });
  runApp(const _PreviewHost());
}

class _PreviewHost extends StatefulWidget {
  const _PreviewHost();

  @override
  State<_PreviewHost> createState() => _PreviewHostState();
}

class _PreviewHostState extends State<_PreviewHost> {
  @override
  void reassemble() {
    super.reassemble();
    _reportedFor = null;
  }

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      debugShowCheckedModeBanner: false,${l10n}
      home: Scaffold(
        body: SafeArea(
          child: Center(
            child: ValueListenableBuilder<String?>(
              valueListenable: _current,
              builder: (context, id, _) {
                final build = id == null ? null : _previews[id];
                if (build == null) return const Text('Select a widget in Orrery');
                return ${shown};
              },
            ),
          ),
        ),
      ),
    );
  }
}

class _ErrorCard extends StatelessWidget {
  const _ErrorCard(this.message);

  final String message;

  @override
  Widget build(BuildContext context) {
    return Directionality(
      textDirection: TextDirection.ltr,
      child: Container(
        color: const Color(0xFFFDECEA),
        padding: const EdgeInsets.all(12),
        child: Text(message, style: const TextStyle(color: Color(0xFFB3261E), fontSize: 13)),
      ),
    );
  }
}
`
}

/** Writes `<root>/.dart_tool/ccm_preview/main.dart` only when the content changed. */
export async function writeHost(root: string, source: string): Promise<{ file: string; changed: boolean }> {
  const dir = path.join(root, HOST_DIR)
  const file = path.join(dir, HOST_FILE)
  const old = await fs.readFile(file, 'utf8').catch(() => null)
  if (old === source) return { file, changed: false }
  await fs.mkdir(dir, { recursive: true })
  await fs.writeFile(file, source)
  return { file, changed: true }
}
